let code;

switch(code){
    case "HTML":
        console.log("拡張子は.HTMLです");
        break;
    case "CSS":
        console.log("拡張子.cssです");
        break;
    case "JavaScript":
        console.log("拡張子は.jsです");
        break;
    default:
        console.log("分からないファイルです");
}

